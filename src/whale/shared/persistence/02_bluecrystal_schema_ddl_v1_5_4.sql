-- -----------------------------------------------------------------------------
-- View column comment coverage check
-- This block guarantees that every view column in whale.vw_% has a
-- non-empty COMMENT ON COLUMN persisted in pg_description.
-- -----------------------------------------------------------------------------
DO $$
DECLARE
    missing_count INTEGER;
    missing_detail TEXT;
BEGIN
    SELECT COUNT(*),
           string_agg(format('%I.%I', c.relname, a.attname), ', ' ORDER BY c.relname, a.attnum)
      INTO missing_count, missing_detail
    FROM pg_catalog.pg_class c
    JOIN pg_catalog.pg_namespace n
      ON n.oid = c.relnamespace
    JOIN pg_catalog.pg_attribute a
      ON a.attrelid = c.oid
     AND a.attnum > 0
     AND NOT a.attisdropped
    LEFT JOIN pg_catalog.pg_description d
      ON d.objoid = c.oid
     AND d.objsubid = a.attnum
    WHERE n.nspname = 'whale'
      AND c.relkind IN ('v', 'm')
      AND c.relname LIKE 'vw\_%' ESCAPE '\'
      AND NULLIF(btrim(d.description), '') IS NULL;

    IF missing_count > 0 THEN
        RAISE EXCEPTION 'Missing COMMENT ON COLUMN for % view columns: %', missing_count, missing_detail;
    END IF;
END $$;


