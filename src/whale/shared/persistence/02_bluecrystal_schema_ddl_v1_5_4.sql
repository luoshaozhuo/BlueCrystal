CREATE OR REPLACE VIEW whale.vw_task_full AS
WITH item_agg AS (
    SELECT task_point_table_id,
           count(*)::bigint AS task_item_count,
           jsonb_agg(protocol_point_item_id ORDER BY scan_order, protocol_point_item_id) AS point_item_ids_json
    FROM whale.task_point_item
    WHERE enabled = TRUE AND valid_to IS NULL
    GROUP BY task_point_table_id
), param_agg AS (
    SELECT v.task_config_id,
           jsonb_object_agg(d.param_identifier, v.param_value ORDER BY d.param_identifier) AS params_json
    FROM whale.task_param_value v
    JOIN whale.task_param_def d ON d.task_param_def_id = v.task_param_def_id
    WHERE v.enabled = TRUE AND v.valid_to IS NULL AND d.enabled = TRUE AND d.valid_to IS NULL
    GROUP BY v.task_config_id
)
SELECT
    t.task_id,
    t.task_identifier,
    c.cfg_connection_id AS connection_id,
    a.ast_asset_id AS asset_id,
    a.asset_identifier,
    a.name_zh AS asset_name,
    at.code AS asset_type_code,
    at.name_zh AS asset_type_name,
    protocol.code AS protocol,
    task_type.code AS task_type,
    status.code AS task_status,
    t.valid_from::date AS start_date,
    t.valid_to::date AS end_date,
    COALESCE(item_agg.task_item_count, 0)::bigint AS task_item_count,
    (jsonb_build_object('timeout_ms', tc.timeout_ms, 'retry_count', tc.retry_count) || COALESCE(param_agg.params_json, '{}'::jsonb)) AS task_params_json,
    COALESCE(item_agg.point_item_ids_json, '[]'::jsonb) AS point_item_ids_json,
    CASE protocol.code WHEN 'MODBUS' THEN 'vw_modbus_point_item' WHEN 'OPCUA' THEN 'vw_opcua_point_item' WHEN 'ADS' THEN 'vw_ads_point_item' WHEN 'IEC101' THEN 'vw_iec101_point_item' WHEN 'IEC104' THEN 'vw_iec104_point_item' WHEN 'IEC61850_MMS' THEN 'vw_iec61850_mms_point_item' WHEN 'IEC61850_GOOSE' THEN 'vw_iec61850_goose_point_item' WHEN 'IEC61850_SV' THEN 'vw_iec61850_sv_point_item' WHEN 'MQTT' THEN 'vw_mqtt_point_item' WHEN 'HTTP_REST' THEN 'vw_http_rest_point_item' END AS point_item_view_name
FROM whale.task t
JOIN whale.task_config tc ON tc.task_id = t.task_id AND tc.enabled AND tc.valid_to IS NULL
JOIN whale.cfg_connection c ON c.cfg_connection_id = tc.cfg_connection_id
JOIN whale.ast_asset a ON a.ast_asset_id = c.asset_id
JOIN whale.ref_code at ON at.ref_code_id = a.asset_type_ref_id
JOIN whale.ref_code protocol ON protocol.ref_code_id = c.protocol_ref_id
JOIN whale.cfg_protocol_task_type_mapping map ON map.cfg_protocol_task_type_mapping_id = tc.cfg_protocol_task_type_mapping_id
JOIN whale.ref_code task_type ON task_type.ref_code_id = map.task_type_ref_id
JOIN whale.ref_code status ON status.ref_code_id = t.task_status_ref_id
LEFT JOIN item_agg ON item_agg.task_point_table_id = tc.task_point_table_id
LEFT JOIN param_agg ON param_agg.task_config_id = tc.task_config_id
WHERE t.valid_to IS NULL
ORDER BY protocol.sort_order, a.asset_identifier, task_type.sort_order, t.task_id;
COMMENT ON VIEW whale.vw_task_full IS '【配置数据】任务执行视图。外部程序通过 connection_id、task_params_json、point_item_view_name、point_item_ids_json 执行任务，不需要访问原始任务表。';
