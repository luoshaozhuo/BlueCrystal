RETURNS BIGINT AS $$
DECLARE
    v_code TEXT;
    v_id BIGINT;
BEGIN
    SELECT code INTO v_code FROM whale.ref_code WHERE ref_code_id = p_data_type_ref_id;
    SELECT ref_code_id INTO v_id FROM whale.ref_code WHERE ref_type='PROTOCOL_DATA_TYPE' AND code=v_code AND enabled=true ORDER BY ref_code_id DESC LIMIT 1;
    IF v_id IS NULL THEN
        SELECT ref_code_id INTO v_id FROM whale.ref_code WHERE ref_type='PROTOCOL_DATA_TYPE' AND code='FLOAT32' AND enabled=true ORDER BY ref_code_id DESC LIMIT 1;
    END IF;
    RETURN v_id;
END;
$$ LANGUAGE plpgsql;

