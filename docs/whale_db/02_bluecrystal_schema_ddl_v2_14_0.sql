CREATE OR REPLACE FUNCTION whale.validate_remote_connection()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE v_protocol TEXT; v_role TEXT;
BEGIN
    SELECT p.protocol_identifier, r.code INTO v_protocol, v_role
      FROM whale.meta_comm_protocol_role r
      JOIN whale.meta_comm_protocol p ON p.meta_comm_protocol_id=r.meta_comm_protocol_id
     WHERE r.meta_comm_protocol_role_id=NEW.meta_comm_protocol_role_id;
    IF v_protocol='IEC104' AND v_role<>'CONTROLLED_STATION' THEN
        RAISE EXCEPTION 'comm_* 仅描述 Remote Connection；IEC104 当前只允许远端 CONTROLLED_STATION，当前角色=%', v_role;
    ELSIF v_protocol='ADS' AND v_role<>'SERVER' THEN
        RAISE EXCEPTION 'comm_* 仅描述 Remote Connection；ADS 当前只允许远端 SERVER，当前角色=%', v_role;
    ELSIF v_protocol NOT IN ('IEC104','ADS') THEN
        RAISE EXCEPTION '当前版本 comm_* 仅支持 IEC104 与 ADS，当前协议=%', v_protocol;
    END IF;
    RETURN NEW;
END;
$$;
COMMENT ON FUNCTION whale.validate_remote_connection() IS '限制 comm_* 仅保存当前支持协议的外部 Remote Connection，不混入 Whale 本地 Server。';

CREATE OR REPLACE FUNCTION whale.validate_src_point_item_update_mode()
