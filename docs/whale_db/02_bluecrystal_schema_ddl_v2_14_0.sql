CREATE OR REPLACE FUNCTION whale.validate_protocol_point_detail()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    v_protocol TEXT;
    v_addressing_mode TEXT;
BEGIN
    IF TG_TABLE_NAME LIKE 'src_%' THEN
        IF TG_TABLE_NAME LIKE '%iec104%' THEN
            SELECT p.protocol_identifier INTO v_protocol
              FROM whale.src_point_table_item i
              JOIN whale.src_point_table t ON t.src_point_table_id=i.src_point_table_id
              JOIN whale.comm_connection c ON c.comm_connection_id=t.comm_connection_id
              JOIN whale.meta_comm_protocol_role r ON r.meta_comm_protocol_role_id=c.meta_comm_protocol_role_id
              JOIN whale.meta_comm_protocol p ON p.meta_comm_protocol_id=r.meta_comm_protocol_id
             WHERE i.src_point_table_item_id=NEW.src_point_table_item_id;
            IF v_protocol IS DISTINCT FROM 'IEC104' THEN RAISE EXCEPTION 'IEC104 Source 明细只能扩展 IEC104 Source 点'; END IF;
            IF NEW.periodic_transmission_enabled AND NEW.periodic_interval_ms IS NULL THEN RAISE EXCEPTION '启用 IEC104 周期传输时 periodic_interval_ms 必填'; END IF;
        ELSE
            SELECT p.protocol_identifier, a.code INTO v_protocol, v_addressing_mode
              FROM whale.src_point_table_item i
              JOIN whale.src_point_table t ON t.src_point_table_id=i.src_point_table_id
              JOIN whale.comm_connection c ON c.comm_connection_id=t.comm_connection_id
              JOIN whale.meta_comm_protocol_role r ON r.meta_comm_protocol_role_id=c.meta_comm_protocol_role_id
              JOIN whale.meta_comm_protocol p ON p.meta_comm_protocol_id=r.meta_comm_protocol_id
              JOIN whale.meta_ads_addressing_mode a ON a.meta_ads_addressing_mode_id=NEW.meta_ads_addressing_mode_id
             WHERE i.src_point_table_item_id=NEW.src_point_table_item_id;
            IF v_protocol IS DISTINCT FROM 'ADS' THEN RAISE EXCEPTION 'ADS Source 明细只能扩展 ADS Source 点'; END IF;
            IF v_addressing_mode='SYMBOL' AND NEW.symbol_name IS NULL THEN RAISE EXCEPTION 'ADS SYMBOL 寻址要求 symbol_name'; END IF;
            IF v_addressing_mode='INDEX' AND (NEW.index_group IS NULL OR NEW.index_offset IS NULL) THEN RAISE EXCEPTION 'ADS INDEX 寻址要求 index_group 与 index_offset'; END IF;
        END IF;
    ELSE
        IF TG_TABLE_NAME LIKE '%iec104%' THEN
            SELECT p.protocol_identifier INTO v_protocol
              FROM whale.sink_point_table_item i
              JOIN whale.sink_point_table t ON t.sink_point_table_id=i.sink_point_table_id
              JOIN whale.comm_connection c ON c.comm_connection_id=t.comm_connection_id
              JOIN whale.meta_comm_protocol_role r ON r.meta_comm_protocol_role_id=c.meta_comm_protocol_role_id
              JOIN whale.meta_comm_protocol p ON p.meta_comm_protocol_id=r.meta_comm_protocol_id
             WHERE i.sink_point_table_item_id=NEW.sink_point_table_item_id;
            IF v_protocol IS DISTINCT FROM 'IEC104' THEN RAISE EXCEPTION 'IEC104 Sink 明细只能扩展 IEC104 Sink 点'; END IF;
        ELSE
            SELECT p.protocol_identifier, a.code INTO v_protocol, v_addressing_mode
              FROM whale.sink_point_table_item i
              JOIN whale.sink_point_table t ON t.sink_point_table_id=i.sink_point_table_id
              JOIN whale.comm_connection c ON c.comm_connection_id=t.comm_connection_id
              JOIN whale.meta_comm_protocol_role r ON r.meta_comm_protocol_role_id=c.meta_comm_protocol_role_id
              JOIN whale.meta_comm_protocol p ON p.meta_comm_protocol_id=r.meta_comm_protocol_id
              JOIN whale.meta_ads_addressing_mode a ON a.meta_ads_addressing_mode_id=NEW.meta_ads_addressing_mode_id
             WHERE i.sink_point_table_item_id=NEW.sink_point_table_item_id;
            IF v_protocol IS DISTINCT FROM 'ADS' THEN RAISE EXCEPTION 'ADS Sink 明细只能扩展 ADS Sink 点'; END IF;
            IF v_addressing_mode='SYMBOL' AND NEW.symbol_name IS NULL THEN RAISE EXCEPTION 'ADS SYMBOL 寻址要求 symbol_name'; END IF;
            IF v_addressing_mode='INDEX' AND (NEW.index_group IS NULL OR NEW.index_offset IS NULL) THEN RAISE EXCEPTION 'ADS INDEX 寻址要求 index_group 与 index_offset'; END IF;
        END IF;
    END IF;
    RETURN NEW;
END;
$$;
COMMENT ON FUNCTION whale.validate_protocol_point_detail() IS '校验 IEC104/ADS 协议 PointItemDetail 与上级 Connection 协议及协议字段的一致性。';

