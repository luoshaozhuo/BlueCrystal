CREATE OR REPLACE FUNCTION whale.validate_task_lifecycle_config_presence()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
DECLARE v_task_ids BIGINT[]; v_task_id BIGINT; v_count INTEGER;
BEGIN
    IF TG_TABLE_NAME='task_data_exchange' THEN
      IF TG_OP='DELETE' THEN v_task_ids:=ARRAY[OLD.task_data_exchange_id]; ELSE v_task_ids:=ARRAY[NEW.task_data_exchange_id]; END IF;
    ELSE
      v_task_ids:=ARRAY[CASE WHEN TG_OP<>'DELETE' THEN NEW.task_data_exchange_id END, CASE WHEN TG_OP<>'INSERT' THEN OLD.task_data_exchange_id END];
    END IF;
    FOREACH v_task_id IN ARRAY v_task_ids LOOP
      IF v_task_id IS NULL THEN CONTINUE; END IF;
      IF EXISTS(SELECT 1 FROM whale.task_data_exchange WHERE task_data_exchange_id=v_task_id) THEN
        SELECT COUNT(*) INTO v_count FROM whale.task_lifecycle_config WHERE task_data_exchange_id=v_task_id;
        IF v_count<>1 THEN RAISE EXCEPTION '数据交换任务 % 必须且只能有一条 task_lifecycle_config，当前数量=%', v_task_id, v_count; END IF;
      END IF;
    END LOOP;
    IF TG_OP='DELETE' THEN RETURN OLD; END IF; RETURN NEW;
END; $$;
