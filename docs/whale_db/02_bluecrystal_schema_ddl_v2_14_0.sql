CREATE OR REPLACE FUNCTION whale.validate_data_exchange_task()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
DECLARE
    v_connection_role BIGINT; v_operation_role BIGINT;
    v_requires_acquisition BOOLEAN; v_requires_delivery BOOLEAN;
    v_source_connection BIGINT; v_sink_connection BIGINT;
    v_trigger_code TEXT; v_allowed_triggers TEXT[];
BEGIN
    SELECT meta_comm_protocol_role_id INTO v_connection_role FROM whale.comm_connection WHERE comm_connection_id=NEW.comm_connection_id;
    SELECT meta_comm_protocol_role_id, requires_acquisition_point_table, requires_delivery_point_table, allowed_trigger_modes
      INTO v_operation_role, v_requires_acquisition, v_requires_delivery, v_allowed_triggers
      FROM whale.meta_task_protocol_operation WHERE meta_task_protocol_operation_id=NEW.meta_task_protocol_operation_id;
    IF v_connection_role IS DISTINCT FROM v_operation_role THEN RAISE EXCEPTION '任务协议操作必须属于该 Remote Connection 的 Endpoint 协议角色'; END IF;
    IF v_requires_acquisition AND NEW.task_acquisition_point_table_id IS NULL THEN RAISE EXCEPTION '当前协议操作要求 Acquisition 任务点表'; END IF;
    IF NOT v_requires_acquisition AND NEW.task_acquisition_point_table_id IS NOT NULL THEN RAISE EXCEPTION '当前协议操作不使用 Acquisition 任务点表'; END IF;
    IF v_requires_delivery AND NEW.task_delivery_point_table_id IS NULL THEN RAISE EXCEPTION '当前协议操作要求 Delivery 任务点表'; END IF;
    IF NOT v_requires_delivery AND NEW.task_delivery_point_table_id IS NOT NULL THEN RAISE EXCEPTION '当前协议操作不使用 Delivery 任务点表'; END IF;
    IF NEW.task_acquisition_point_table_id IS NOT NULL THEN
      SELECT s.comm_connection_id INTO v_source_connection FROM whale.task_acquisition_point_table t JOIN whale.src_point_table s ON s.src_point_table_id=t.src_point_table_id WHERE t.task_acquisition_point_table_id=NEW.task_acquisition_point_table_id;
      IF v_source_connection IS DISTINCT FROM NEW.comm_connection_id THEN RAISE EXCEPTION 'Acquisition 任务点表必须来自任务同一 Remote Connection'; END IF;
    END IF;
    IF NEW.task_delivery_point_table_id IS NOT NULL THEN
      SELECT s.comm_connection_id INTO v_sink_connection FROM whale.task_delivery_point_table t JOIN whale.sink_point_table s ON s.sink_point_table_id=t.sink_point_table_id WHERE t.task_delivery_point_table_id=NEW.task_delivery_point_table_id;
      IF v_sink_connection IS DISTINCT FROM NEW.comm_connection_id THEN RAISE EXCEPTION 'Delivery 任务点表必须来自任务同一 Remote Connection'; END IF;
    END IF;
    SELECT code INTO v_trigger_code FROM whale.meta_task_trigger_mode WHERE meta_task_trigger_mode_id=NEW.meta_task_trigger_mode_id;
    IF NOT (v_trigger_code=ANY(v_allowed_triggers)) THEN RAISE EXCEPTION '触发方式 % 不在该协议操作允许集合中', v_trigger_code; END IF;
    RETURN NEW;
END; $$;
COMMENT ON FUNCTION whale.validate_data_exchange_task() IS '校验任务 Connection、协议操作、Acquisition/Delivery 点表及触发方式。';

